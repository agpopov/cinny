"""Encrypted attachments, spoilers and stickers between two real Matrix devices.

Use a disposable Synapse (HS_URL) and a local app build (APP_URL).
VIDEO_FIXTURE points to a WebM generated by media_stickers.py.
"""
import json
import os
import re
import time
import urllib.request
import uuid
from pathlib import Path
from playwright.sync_api import sync_playwright

HS = os.environ.get('HS_URL', 'http://127.0.0.1:8008')
APP = os.environ.get('APP_URL', 'http://127.0.0.1:18812')
OUT = Path(os.environ.get('TEST_OUTPUT', '/tmp/cinny-encrypted-media'))
OUT.mkdir(parents=True, exist_ok=True)
opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

def api(method, path, token=None, body=None):
    request = urllib.request.Request(HS + path, method=method, headers={
        'Content-Type': 'application/json', **({'Authorization': 'Bearer ' + token} if token else {}),
    })
    with opener.open(request, json.dumps(body).encode() if body is not None else None, timeout=30) as response:
        return json.loads(response.read() or b'{}')

def check(label, condition=True):
    assert condition, label
    print('PASS ' + label, flush=True)

run = uuid.uuid4().hex[:8]
a, b = [api('POST', '/_matrix/client/v3/register', body={
    'username': prefix + run, 'password': 'pass123', 'auth': {'type': 'm.login.dummy'},
}) for prefix in ['mediaencalice', 'mediaencbob']]
token = a['access_token']
room = api('POST', '/_matrix/client/v3/createRoom', token, {
    'room_version': '10', 'name': 'Encrypted media ' + run, 'invite': [b['user_id']],
    'initial_state': [{'type': 'm.room.encryption', 'state_key': '', 'content': {'algorithm': 'm.megolm.v1.aes-sha2'}}],
})['room_id']
api('POST', f'/_matrix/client/v3/join/{room}', b['access_token'], {})

def events():
    return api('GET', f'/_matrix/client/v3/rooms/{room}/messages?dir=b&limit=100', token)['chunk']

def next_encrypted(previous):
    for _ in range(120):
        found = next((event for event in events() if event['event_id'] not in previous and event['type'] == 'm.room.encrypted'), None)
        if found:
            return found
        time.sleep(.25)
    raise AssertionError('Encrypted event not received')

png = (Path(__file__).resolve().parents[2] / 'public/res/stickers/cats/cat_face.png').read_bytes()
clip = Path(os.environ.get('VIDEO_FIXTURE', '/tmp/cinny-4.12.12-media-shots/fixture.webm')).read_bytes()
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(args=['--no-sandbox', '--no-proxy-server'])
    contexts = []
    pages = []
    errors = []
    for session in [a, b]:
        context = browser.new_context(viewport={'width': 1400, 'height': 900})
        contexts.append(context)
        page = context.new_page(); pages.append(page)
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.route('**/config.json', lambda route: route.fulfill(json={
            'homeserverList': [HS], 'allowCustomHomeservers': True, 'hashRouter': {'enabled': False, 'basename': '/'},
        }))
        page.goto(APP + '/config.json')
        page.evaluate('''s => {
          localStorage.setItem('cinny_access_token', s.access_token);
          localStorage.setItem('cinny_device_id', s.device_id);
          localStorage.setItem('cinny_user_id', s.user_id);
          localStorage.setItem('cinny_hs_base_url', s.hs);
        }''', {**session, 'hs': HS})
        page.goto(APP + '/home/' + room + '/')
        page.locator('[data-editable-name="RoomInput"]').wait_for(timeout=40000)
        page.wait_for_timeout(2500); page.keyboard.press('Escape')
    sender, receiver = pages
    try:
        for filename, data, mime, video in [('secret.png', png, 'image/png', False), ('secret.webm', clip, 'video/webm', True)]:
            unique = run + '-' + filename
            before = {event['event_id'] for event in events()}
            with sender.expect_file_chooser() as chosen:
                sender.get_by_role('button', name='Прикрепить', exact=True).click()
                sender.get_by_text('Файл', exact=True).click()
            chosen.value.set_files({'name': unique, 'mimeType': mime, 'buffer': data})
            sender.get_by_role('button', name='Спойлер', exact=True).click()
            sender.get_by_role('button', name='Отправить', exact=True).wait_for(timeout=30000)
            sender.get_by_role('button', name='Отправить', exact=True).click()
            event = next_encrypted(before)
            check('server receives only ciphertext for ' + filename, unique not in json.dumps(event['content']) and 'mxc://' not in json.dumps(event['content']))
            for index, page in enumerate(pages):
                row = page.locator('[data-message-id="' + event['event_id'] + '"]')
                row.get_by_role('button', name='Спойлер', exact=True).wait_for(timeout=40000)
                check(f'device {index} hides encrypted spoiler ' + filename)
                row.get_by_role('button', name='Спойлер', exact=True).click()
                if video:
                    page.wait_for_function('(row) => row.querySelector("video")?.videoWidth === 160', arg=row.element_handle())
                    check(f'device {index} decrypts video to a Blob URL', row.locator('video').get_attribute('src').startswith('blob:'))
                else:
                    page.wait_for_function('(row) => Array.from(row.querySelectorAll("img")).some(img => img.naturalWidth === 256)', arg=row.element_handle())
                    check(f'device {index} decrypts image to a Blob URL', row.locator('img').last.get_attribute('src').startswith('blob:'))
            check('both devices display decrypted ' + filename)
        before = {event['event_id'] for event in events()}
        sender.get_by_role('button', name='Стикеры', exact=True).click()
        sender.locator('button[data-emoji-data="builtin-sticker:cats/cat_face"]').click()
        event = next_encrypted(before)
        check('sticker event is encrypted', 'Котик' not in json.dumps(event['content'], ensure_ascii=False))
        row = receiver.locator('[data-message-id="' + event['event_id'] + '"]')
        row.wait_for(timeout=40000)
        receiver.wait_for_function('(row) => Array.from(row.querySelectorAll("img")).some(img => img.naturalWidth === 256)', arg=row.element_handle())
        check('second device renders encrypted sticker event')
        receiver.screenshot(path=str(OUT / 'encrypted-media.png'))
        receiver.reload(); receiver.locator('[data-editable-name="RoomInput"]').wait_for(timeout=40000)
        receiver.wait_for_function('(id) => Array.from(document.querySelectorAll(`[data-message-id="${id}"] img`)).some(img => img.naturalWidth === 256)', arg=event['event_id'])
        check('encrypted sticker survives reload')
        check('encrypted media exchange has no script errors', not errors)
    except Exception:
        for index, page in enumerate(pages):
            page.screenshot(path=str(OUT / f'failure-{index}.png'))
            (OUT / f'failure-{index}.txt').write_text(page.locator('body').inner_text() + '\n' + repr(errors))
        raise
    finally:
        for context in contexts:
            context.close()
        browser.close()
